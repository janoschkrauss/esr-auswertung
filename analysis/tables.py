"""LaTeX table of the DPPH fit results for the report appendix, from results/dpph_fits.csv (no number typed by hand).

    cd analysis && python3 tables.py
"""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

rows = list(csv.DictReader(open(ROOT / "results" / "dpph_fits.csv")))
order = ["07b", "08", "09", "10", "11", "12", "13", "14", "15", "16", "16b", "17b", "18", "24", "25", "26", "27", "20"]
rows.sort(key=lambda r: order.index(r["scan"]))

lines = []
for r in rows:
    arrow = r"$\uparrow$" if r["direction"] == "1" else r"$\downarrow$"
    rms_ratio = float(r["rms_L"]) / float(r["rms_C"])
    lines.append(
        f"{r['scan']} & {float(r['mod_V']):g} & {r['X382A_dB']} & {r['X375A_dB']} & {arrow} & "
        f"{float(r['pp_uV']):.1f} & {float(r['U0_C']):.4f} & {float(r['G_C_mV']):.2f}({max(1, round(float(r['dG_C_mV'])*100)):d}) & "
        f"{float(r['lam_mV']):.1f}({max(1, round(float(r['dlam_mV'])*10)):d}) & {float(r['phi_C_deg']):.0f} & "
        f"{float(r['G_L_mV']):.2f} & {float(r['phi_L_deg']):.0f} & {rms_ratio:.1f} \\\\")

tex = r"""% generated by analysis/tables.py -- do not edit by hand
\begin{center}
  \footnotesize\setlength{\tabcolsep}{3.4pt}\captionsetup{hypcap=false}
  \captionof{table}{Fit results of all analyzed DPPH scans. Convolution model (\cref{eq:convolution}): position $U_0$, intrinsic
  HWHM $G$, length $\lambda$ of the field distribution, mixing angle $\varphi_\ast=\operatorname{atan2}(d,a)$. Simple
  Lorentzian fit: $G_\mathrm{L}$, $\varphi_\mathrm{L}$. Last column: ratio of the residual rms of both fits.
  \qty{1}{mV} corresponds to \qty{60.76}{\micro T}; attenuators in dB; arrow: sweep direction.}
  \label{tab:dpphfits}
  \sisetup{table-number-alignment=center, uncertainty-mode=compact}
  \begin{tabular}{@{}l S[table-format=1.2] S[table-format=2.0] S[table-format=2.0] c S[table-format=3.1] S[table-format=1.4] S[table-format=1.2(2)] S[table-format=2.1(2)] S[table-format=-3.0] S[table-format=1.2] S[table-format=-3.0] S[table-format=1.1]@{}}
    \toprule
    Scan & {Mod.\ (V)} & {X382A} & {X375A} & & {$S_\mathrm{pp}$ (\si{\micro V})} & {$U_0$ (V)} & {$G$ (mV)} & {$\lambda$ (mV)}
      & {$\varphi_\ast$ (\si{\degree})} & {$G_\mathrm{L}$ (mV)} & {$\varphi_\mathrm{L}$ (\si{\degree})} & {$\frac{\mathrm{rms_L}}{\mathrm{rms}_\ast}$} \\
    \midrule
""" + "\n".join("    " + z for z in lines) + r"""
    \bottomrule
  \end{tabular}
\end{center}
"""
(ROOT / "report" / "parts" / "tab_dpph.tex").write_text(tex)
print("tab_dpph.tex")
